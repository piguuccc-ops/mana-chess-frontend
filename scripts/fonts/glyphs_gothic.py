SPACE_ADVANCE = 4

def acute(w):
    c = max(0, (w - 3) // 2)
    top = ['.'] * max(w, c + 3); bot = ['.'] * max(w, c + 3)
    top[c + 1] = top[c + 2] = '#'
    bot[c] = bot[c + 1] = '#'
    return [''.join(top), ''.join(bot)]

def umlaut(w):
    c = (w - 5) // 2
    row = ['.'] * w
    for x in (c, c + 1, c + 3, c + 4):
        if 0 <= x < w: row[x] = '#'
    return [''.join(row), ''.join(row)]

def dacute(w):
    c = (w - 6) // 2
    top = ['.'] * w; bot = ['.'] * w
    for x in (c + 1, c + 2, c + 4, c + 5):
        if 0 <= x < w: top[x] = '#'
    for x in (c, c + 1, c + 3, c + 4):
        if 0 <= x < w: bot[x] = '#'
    return [''.join(top), ''.join(bot)]

ACCENTED = {
    'á': ('a', acute), 'é': ('e', acute), 'ó': ('o', acute), 'ú': ('u', acute),
    'ö': ('o', umlaut), 'ü': ('u', umlaut), 'ő': ('o', dacute), 'ű': ('u', dacute),
    'Á': ('A', acute), 'É': ('E', acute), 'Í': ('I', acute), 'Ó': ('O', acute),
    'Ú': ('U', acute), 'Ö': ('O', umlaut), 'Ü': ('U', umlaut), 'Ő': ('O', dacute),
    'Ű': ('U', dacute),
}

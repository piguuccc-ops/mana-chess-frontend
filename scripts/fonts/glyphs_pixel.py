# Accents: (row offset above the base glyph top gap, pattern generator)
def acute(w):
    c = w // 2
    top = ['.'] * w; bot = ['.'] * w
    top[min(w - 1, c + 1)] = '#'; bot[c] = '#'
    return [''.join(top), ''.join(bot)]

def umlaut(w):
    c = w // 2
    row = ['.'] * w
    row[max(0, c - 1)] = '#'; row[min(w - 1, c + 1)] = '#'
    return [''.join(row)]

def dacute(w):
    c = w // 2
    top = ['.'] * w; bot = ['.'] * w
    for x in (c, c + 2):
        if 0 <= x < w: top[x] = '#'
    for x in (c - 1, c + 1):
        if 0 <= x < w: bot[x] = '#'
    return [''.join(top), ''.join(bot)]

